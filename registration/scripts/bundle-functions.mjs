// Builds single-file copies of Edge Functions for pasting into the Supabase dashboard editor
// (Edge Functions → Deploy a new function → Via editor), for when the CLI isn't available.
// Usage: npm run bundle:functions [-- name ...]   Needs Deno 2.4+ on the PATH.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const names = process.argv.slice(2).length ? process.argv.slice(2) : ['send-ballots', 'checkout-ballot'];
const tmp = mkdtempSync(join(tmpdir(), 'fnbundle-'));

for (const name of names) {
  const out = join(tmp, `${name}.js`);
  execFileSync('deno', ['bundle', '--node-modules-dir=none', '--no-config', '--platform', 'deno', '--external', 'npm:*',
    '-o', out, `supabase/functions/${name}/index.ts`], { stdio: 'inherit' });
  writeFileSync(`supabase/dashboard-deploy/${name}.ts`,
    `// Single-file build of supabase/functions/${name} for the Supabase dashboard editor.\n` +
    '// Generated by `npm run bundle:functions`. Edit the source in supabase/functions, not this file.\n' +
    readFileSync(out, 'utf8'));
  console.log(`wrote supabase/dashboard-deploy/${name}.ts`);
}
