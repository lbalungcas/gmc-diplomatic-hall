// Inserts fake registrants for testing (default 20; `npm run seed:fake -- 300` for a load test).
// Answers are generated from the event's current form, so they look like real submissions.
// Uses the service role key from registration/.env — run on your machine only, never in CI/Netlify.
// Fake rows use @example.org addresses so they're easy to find and delete:
//   delete from registrations where email like '%@example.org';
import { createClient } from '@supabase/supabase-js';
import { readFileSync } from 'node:fs';
import { extractCore, OTHER_PREFIX, questions, resolveForm, sectionPath } from '../supabase/functions/_shared/form.ts';

try {
  for (const line of readFileSync(new URL('../.env', import.meta.url), 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z_]+)\s*=\s*(.*)\s*$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
  }
} catch {
  /* no .env — rely on the environment */
}

const url = process.env.SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) {
  console.error('Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY (see .env.example).');
  process.exit(1);
}

const count = Number(process.argv[2] ?? 20);
const slug = process.env.VITE_EVENT_SLUG || 'yim-2026';
const db = createClient(url, key, { auth: { persistSession: false } });

const { data: event, error: eventError } = await db.from('events').select('form_schema').eq('slug', slug).single();
if (eventError) {
  console.error(eventError.message);
  process.exit(1);
}
const form = resolveForm(event.form_schema);

const FIRST = ['Maria', 'Jose', 'Angelica', 'Paolo', 'Aiko', 'Ravi', 'Siti', 'Liam', 'Nguyen', 'Grace', 'Tomas', 'Leila', 'Kofi', 'Ana', 'Miguel', 'Hana'];
const LAST = ['Santos', 'Reyes', 'Cruz', 'Tanaka', 'Sharma', 'Rahman', 'Garcia', 'Lim', 'Tran', 'Mendoza', 'Okafor', 'Bautista'];
const ORGS = ['Department of Social Welfare and Development', 'Plan International', 'Save the Children', 'UP Diliman', 'Youth for Change PH', 'Independent'];
const COUNTRIES = [['Philippines', 'Filipino'], ['Indonesia', 'Indonesian'], ['Thailand', 'Thai'], ['Vietnam', 'Vietnamese'], ['India', 'Indian'], ['Netherlands', 'Dutch']];
const pick = (a, i) => a[i % a.length];

function fakeAnswers(i) {
  const first = pick(FIRST, i);
  const last = pick(LAST, i * 7 + 3);
  const [country, nationality] = pick(COUNTRIES, i * 3);
  const age = i % 6 === 0 ? 14 + (i % 4) : 18 + ((i * 7) % 40);
  const byField = {
    full_name: `${first} ${last}`,
    preferred_name: first,
    email: `test+${i}-${first.toLowerCase()}@example.org`,
    phone: `+63 917 555 ${String(1000 + i).slice(-4)}`,
    organization: pick(ORGS, i),
    country,
    nationality,
    age: String(age),
  };
  const answers = {};
  for (const q of questions(form)) {
    if (q.mapsTo && byField[q.mapsTo]) answers[q.id] = byField[q.mapsTo];
    else if (q.kind === 'radio') answers[q.id] = q.options[(i + q.id.length) % q.options.length].label;
    else if (q.kind === 'checkbox') {
      const opts = q.options.filter((_, oi) => (i + oi) % 2 === 0 || q.options.length === 1).map((o) => o.label);
      answers[q.id] = opts.length ? opts : [q.options[0].label];
      if (q.allowOther && i % 9 === 0) answers[q.id].push(`${OTHER_PREFIX}Something else`);
    } else if (q.kind === 'email') answers[q.id] = `test+x${i}@example.org`;
    else if (q.kind === 'phone') answers[q.id] = '+63 917 555 0000';
    else if (q.kind === 'number') answers[q.id] = '1';
    else answers[q.id] = q.kind === 'paragraph' ? 'Test answer generated by seed-fake.' : 'Test';
  }
  // Keep only answers on the path this respondent would take (e.g. Deal Corner "No" skips section 7).
  const visited = new Set(sectionPath(form, answers).flatMap((s) => s.blocks.map((b) => b.id)));
  return Object.fromEntries(Object.entries(answers).filter(([id]) => visited.has(id)));
}

let created = 0;
let duplicates = 0;
for (let i = 0; i < count; i++) {
  const answers = fakeAnswers(i);
  const core = extractCore(form, answers);
  const minor = core.age !== null && core.age < 18;
  const p = {
    ...core,
    answers,
    guardian_name: minor ? `Parent of ${core.preferred_name ?? core.full_name}` : null,
    guardian_email: minor ? `test+guardian${i}@example.org` : null,
    guardian_consent: minor,
    photo_consent: i % 4 !== 0,
    privacy_consent: true,
  };
  const { data, error } = await db.rpc('create_registration', { p_event_slug: slug, p });
  if (error) {
    console.error(`row ${i}:`, error.message);
    continue;
  }
  if (data.outcome === 'created') created++;
  else if (data.outcome === 'duplicate') duplicates++;
  else console.error(`row ${i}:`, data.outcome);
}
console.log(`Created ${created}, already existed ${duplicates}. (No emails are sent by this script.)`);
